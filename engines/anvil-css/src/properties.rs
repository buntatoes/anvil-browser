fn table() -> &'static HashMap<&'static str, &'static PropertyDef> {
    static TABLE: OnceLock<HashMap<&'static str, &'static PropertyDef>> = OnceLock::new();
    TABLE.get_or_init(|| PROPERTIES.iter().map(|p| (p.name, p)).collect())
}

/// Look up a property by name (ASCII case-insensitive).
pub fn property(name: &str) -> Option<&'static PropertyDef> {
    let t = table();
    if let Some(p) = t.get(name) {
        return Some(p);
    }
    t.get(name.to_ascii_lowercase().as_str()).copied()
}

/// True when `name` inherits by default. Custom properties inherit.
/// Unknown properties return `false`.
pub fn is_inherited(name: &str) -> bool {
    name.starts_with("--") || property(name).is_some_and(|p| p.inherited)
}
