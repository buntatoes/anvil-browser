//! The property table: name, inherited flag, initial value, and grammar for
//! commonly used CSS properties.
//!
//! The table is written by hand in this file from the property definition
//! tables of the CSS modules (CSS 2.2, Backgrounds 3, Box Alignment 3,
//! Flexbox 1, Grid 2, Fonts 4, Text 3/4, Transforms 2, Animations 1/2,
//! Transitions 1/2, UI 4, Logical Properties 1, Anchor Positioning 1,
//! View Transitions 1/2, Masking 1, Motion Path 1, and others). It has no
//! generated parts.
//!
//! The grammars are deliberately coarse. Properties with a simple value
//! type (a length, a color, a keyword list) are checked fully. Shorthands
//! and properties with rich grammars use [`Grammar::Generic`]: every
//! component is type-checked (units, colors, math functions, nested
//! functions) but the order and count of components is left to the style
//! system. Shorthand expansion is not done here.

use std::collections::HashMap;
use std::sync::OnceLock;

/// What a property's value may look like.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Grammar {
    /// One keyword from the list.
    Keywords(&'static [&'static str]),
    /// One to `max` space-separated keywords from the list, each used at
    /// most once (as in `display: inline flex`).
    KeywordList {
        /// Allowed keywords.
        keywords: &'static [&'static str],
        /// Most keywords.
        max: u8,
    },
    /// One length, or one of the keywords; `percent` allows percentages and
    /// `nonneg` rejects negative literals.
    Length {
        /// Allowed keywords.
        keywords: &'static [&'static str],
        /// Percentages allowed.
        percent: bool,
        /// Negative literals rejected.
        nonneg: bool,
    },
    /// One to `max` space-separated lengths or keywords.
    LengthList {
        /// Allowed keywords.
        keywords: &'static [&'static str],
        /// Percentages allowed.
        percent: bool,
        /// Negative literals rejected.
        nonneg: bool,
        /// Most values.
        max: u8,
    },
    /// One number, or one of the keywords.
    Number {
        /// Allowed keywords.
        keywords: &'static [&'static str],
        /// Percentages allowed.
        percent: bool,
        /// Negative literals rejected.
        nonneg: bool,
    },
    /// One integer, or one of the keywords.
    Integer {
        /// Allowed keywords.
        keywords: &'static [&'static str],
    },
    /// One color, or one of the keywords.
    Color {
        /// Allowed keywords besides colors.
        keywords: &'static [&'static str],
    },
    /// A comma-separated list of times.
    TimeList,
    /// Any sequence of type-checked components.
    Generic,
}

/// One row of the property table.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct PropertyDef {
    /// The property name.
    pub name: &'static str,
    /// True when the property inherits by default.
    pub inherited: bool,
    /// The initial value as CSS text. Shorthands say "see longhands".
    pub initial: &'static str,
    /// The value grammar.
    pub grammar: Grammar,
    /// True for a shorthand.
    pub shorthand: bool,
}

