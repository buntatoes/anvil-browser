const fn kw(list: &'static [&'static str]) -> Grammar {
    Grammar::Keywords(list)
}

const fn len(keywords: &'static [&'static str], percent: bool, nonneg: bool) -> Grammar {
    Grammar::Length {
        keywords,
        percent,
        nonneg,
    }
}

const fn lens(keywords: &'static [&'static str], percent: bool, nonneg: bool, max: u8) -> Grammar {
    Grammar::LengthList {
        keywords,
        percent,
        nonneg,
        max,
    }
}

const fn num(keywords: &'static [&'static str], percent: bool, nonneg: bool) -> Grammar {
    Grammar::Number {
        keywords,
        percent,
        nonneg,
    }
}

const fn int(keywords: &'static [&'static str]) -> Grammar {
    Grammar::Integer { keywords }
}

const fn color(keywords: &'static [&'static str]) -> Grammar {
    Grammar::Color { keywords }
}

const fn p(
    name: &'static str,
    inherited: bool,
    initial: &'static str,
    grammar: Grammar,
) -> PropertyDef {
    PropertyDef {
        name,
        inherited,
        initial,
        grammar,
        shorthand: false,
    }
}

const fn sh(name: &'static str, inherited: bool, grammar: Grammar) -> PropertyDef {
    PropertyDef {
        name,
        inherited,
        initial: "see longhands",
        grammar,
        shorthand: true,
    }
}

