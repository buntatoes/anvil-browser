// Ids by length and first unit: BY_KEY[len * 128 + first] lists the
// words to compare. Built once at load time.
const MAX_WORD = 11;
const BY_KEY = [];
let fill = 0;
while (fill < (MAX_WORD + 1) * 128) {
  BY_KEY.push(null);
  fill = fill + 1;
}
let wi = 0;
while (wi < WORD_UNITS.length) {
  const w = WORD_UNITS[wi];
  const key = w.length * 128 + w[0];
  if (BY_KEY[key] === null) {
    BY_KEY[key] = [];
  }
  BY_KEY[key].push(wi);
  wi = wi + 1;
}

// The id of the word in units[start, end), or -1.
export function wordId(units, start, end) {
  const n = end - start;
  if (n < 2 || n > MAX_WORD) {
    return -1;
  }
  const first = units[start];
  if (first >= 128) {
    return -1;
  }
  const ids = BY_KEY[n * 128 + first];
  if (ids === null) {
    return -1;
  }
  let k = 0;
  while (k < ids.length) {
    const w = WORD_UNITS[ids[k]];
    let j = 1;
    while (j < n && units[start + j] === w[j]) {
      j = j + 1;
    }
    if (j === n) {
      return ids[k];
    }
    k = k + 1;
  }
  return -1;
}

// Reserved everywhere (not `await` or `yield`).
export function isReservedWord(id) {
  return id >= 0 && id <= 35;
}

// Reserved in strict code only (`yield` included).
export function isStrictReservedWord(id) {
  return id === W_YIELD || (id >= W_IMPLEMENTS && id <= W_STATIC);
}
